<!-- The heading above a group's cards in the planner. Deliberately lighter than the sidebar's
     header: the sidebar is where you manage groups, this is a signpost while scrolling. -->
<template>
  <div :id="bandId" class="group-band" :class="{ ungrouped: !group }" :style="colorVars">
    <div class="d-flex align-center ga-2 px-3 py-2">
      <!-- Two keyed icons rather than one with a bound class: Font Awesome swaps the <i> for an
           <svg> Vue no longer owns, so a class flip leaves the chevron pointing the same way. -->
      <v-btn
        class="chevron"
        density="compact"
        icon
        size="small"
        :title="collapsed ? 'Expand group' : 'Collapse group'"
        variant="text"
        @click="$emit('toggle')"
      >
        <span v-if="collapsed" key="shut"><i class="fas fa-chevron-right" /></span>
        <span v-else key="open"><i class="fas fa-chevron-down" /></span>
      </v-btn>
      <span class="band-title text-h6">{{ group?.name ?? 'Ungrouped' }}</span>
      <v-chip class="sf-chip small no-margin factory" variant="tonal">
        <i class="fas fa-industry" />
        <span class="ml-2">{{ count }}</span>
      </v-chip>

      <!-- What the group costs and makes, so a band is worth reading rather than just dividing. -->
      <tooltip :text="`Power generated by this group: ${formatMw(power.produced)}`">
        <v-chip class="sf-chip small no-margin generation" variant="tonal">
          <i class="fas fa-bolt mr-1" /><i class="fas fa-plus" />
          <span class="ml-2">{{ formatMw(power.produced) }}</span>
        </v-chip>
      </tooltip>
      <tooltip :text="`Power consumed by this group: ${formatMw(power.consumed)}`">
        <v-chip class="sf-chip small no-margin consumption" variant="tonal">
          <i class="fas fa-bolt mr-1" /><i class="fas fa-minus" />
          <span class="ml-2">{{ formatMw(power.consumed) }}</span>
        </v-chip>
      </tooltip>
      <tooltip :text="`This group ${power.difference < 0 ? 'draws' : 'has a surplus of'} ${formatMw(Math.abs(power.difference))}`">
        <v-chip
          class="sf-chip small no-margin"
          :class="power.difference < 0 ? 'error' : 'success'"
          variant="tonal"
        >
          <i class="fas fa-balance-scale" />
          <span class="ml-2">{{ formatMw(power.difference) }}</span>
        </v-chip>
      </tooltip>
      <tooltip v-if="problems" :text="`${problems} ${problems === 1 ? 'factory' : 'factories'} in this group needs attention`">
        <v-chip class="sf-chip small error no-margin" variant="tonal">
          <i class="fas fa-exclamation-triangle" />
          <span class="ml-2">{{ problems }}</span>
        </v-chip>
      </tooltip>

      <v-spacer />
      <span v-if="collapsed" class="text-body-2 text-medium-emphasis">
        {{ count }} {{ count === 1 ? 'factory' : 'factories' }} hidden
      </span>
    </div>
  </div>
</template>

<script setup lang="ts">
  import { computed } from 'vue'
  import { Factory, FactoryGroup } from '@/interfaces/planner/FactoryInterface'
  import { groupColorVars } from '@/utils/colors'
  import { calculateTotalPower } from '@/utils/statistics'
  import { formatMw } from '@/utils/numberFormatter'
  import { hasFactoryProblem } from '@/utils/factory-management/status'

  const props = defineProps<{
    group: FactoryGroup | null
    count: number
    collapsed: boolean
    factories: Factory[]
  }>()

  // The band is the only summary a collapsed group has, so it carries the group's own power
  // balance rather than making you open it to find out what it costs.
  const power = computed(() => {
    const totals = calculateTotalPower(props.factories)
    return {
      produced: totals.totalPowerProduced,
      consumed: totals.totalPowerConsumed,
      difference: totals.totalPowerDifference,
    }
  })

  const problems = computed(() => props.factories.filter(hasFactoryProblem).length)

  defineEmits<{ (event: 'toggle'): void }>()

  // Element id so the scroll-spy can see the band and the sidebar can jump to it.
  const bandId = computed(() => `group-${props.group?.id ?? 'ungrouped'}`)

  const colorVars = computed(() => (props.group ? groupColorVars(props.group.color) : {}))
</script>

<style lang="scss" scoped>
.group-band {
  position: relative;
  border-radius: 4px;
  margin-bottom: 8px;
  background-color: var(--sf-group-muted, rgba(255, 255, 255, 0.05));
  // Same 2px the group's cards wear, all the way round: the band reads as the lid of the block
  // below it rather than as a differently-drawn thing that happens to sit above it.
  border: 2px solid var(--sf-group, #6c6c6c);
}

// The top of the trunk the cards hang off, bridging the band's own 8px bottom margin so the line
// runs unbroken from the band's edge into the first card. Ungrouped draws no tree and so no stub —
// see Planner.vue for the rest of the geometry.
.group-band:not(.ungrouped)::after {
  content: '';
  position: absolute;
  left: 0;
  bottom: -8px;
  height: 8px;
  width: 3px;
  background-color: var(--sf-group, #6c6c6c);
}

.chevron {
  font-size: 1.1rem;
}

.band-title {
  font-weight: 500;
}

.ungrouped .band-title {
  color: #bdbdbd;
  font-style: italic;
}
</style>
