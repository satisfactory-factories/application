<!-- The heading above a grouped factory in the planner. Deliberately lighter than the sidebar's
     header: the sidebar is where you manage groups, this says which group the factory on screen
     belongs to, where in it you are, and how the group as a whole is doing. -->
<template>
  <div :id="bandId" class="group-band" data-testid="group-band" :style="colorVars">
    <div class="d-flex align-center flex-wrap ga-2 px-3 py-2">
      <!-- The same swatch the sidebar header carries, and it does the same thing: the band is
           where you are looking when a group's colour turns out to be wrong. -->
      <factory-group-color-menu
        :model-value="group.color"
        @update:model-value="setGroupColor(group.id, $event)"
      />
      <span class="band-title text-h6">{{ group.name }}</span>
      <!-- What the group is, next to its name: where the factory on screen sits in it, and how
           many of its factories are in trouble. What it costs in power is the line below. -->
      <tooltip :text="`Factory ${position} of ${factories.length} in this group`">
        <v-chip class="sf-chip small no-margin factory" data-testid="group-band-position" variant="tonal">
          <i class="fas fa-industry" />
          <span class="ml-2">{{ position }} / {{ factories.length }}</span>
        </v-chip>
      </tooltip>
      <!-- The same chips, icons and colours the Factories Summary and the sidebar use, so one
           tier of trouble looks the same wherever it is counted. -->
      <tooltip
        v-for="chip in statusTally"
        :key="chip.key"
        :text="chip.tooltip"
      >
        <v-chip class="sf-chip small no-margin" :class="chip.class" variant="tonal">
          <i :class="chip.icon" />
          <span class="ml-2">{{ chip.count }}</span>
        </v-chip>
      </tooltip>
    </div>
    <!-- The group's power on a line of its own: tucked into the end of the title row it wrapped
         into whatever corner was left. -->
    <div class="d-flex align-center flex-wrap ga-2 px-3 pb-2" data-testid="group-band-power">
      <tooltip :text="`Power generated by this group: ${formatMw(power.produced)}`">
        <v-chip class="sf-chip small no-margin generation" variant="tonal">
          <i class="fas fa-bolt mr-1" /><i class="fas fa-plus" />
          <span class="ml-2">{{ formatMw(power.produced) }}</span>
        </v-chip>
      </tooltip>
      <tooltip :text="`Power consumed by this group: ${formatMw(power.consumed)}`">
        <v-chip class="sf-chip small no-margin consumption" variant="tonal">
          <i class="fas fa-bolt mr-1" /><i class="fas fa-minus" />
          <span class="ml-2">{{ formatMw(power.consumed) }}</span>
        </v-chip>
      </tooltip>
      <!-- Augmenters in this group boost the whole plan's generation, not this group's, so the
           figure is called out rather than folded into the group's own total. -->
      <tooltip
        v-if="power.boost > 0"
        :text="`Alien Power Augmenters in this group add ${formatMw(power.boost)} to the grid, a percentage of the plan's total generation, counted in the plan's power rather than this group's.`"
      >
        <v-chip class="sf-chip small no-margin circuit-boost" variant="tonal">
          <i class="fas fa-bolt" /><i class="fas fa-arrow-up" />
          <span class="ml-2">{{ formatMw(power.boost) }}</span>
        </v-chip>
      </tooltip>
      <tooltip :text="`This group ${power.difference < 0 ? 'draws' : 'has a surplus of'} ${formatMw(Math.abs(power.difference))}`">
        <v-chip
          class="sf-chip small no-margin"
          :class="power.difference < 0 ? 'error' : 'success'"
          variant="tonal"
        >
          <i class="fas fa-balance-scale" />
          <span class="ml-2">{{ formatMw(power.difference) }}</span>
        </v-chip>
      </tooltip>
    </div>
    <!-- Every factory in the group, so a jump to any of them is one click rather than a walk
         through the pagers. The one on screen is marked rather than left out, so the row reads as
         the group's running order. -->
    <div
      ref="factoryRow"
      class="d-flex align-center flex-wrap ga-2 px-3 pb-2 band-factories"
      data-testid="group-band-factories"
    >
      <v-chip
        v-for="factory in factories"
        :key="factory.id"
        class="sf-chip small no-margin band-factory flex-shrink-0"
        :class="['sf-chip-clickable', { 'band-factory-current': factory.id === currentId }]"
        :data-testid="`group-band-factory-${factory.id}`"
        variant="tonal"
        v-bind="factory.id === currentId ? {} : { onClick: () => emit('go', factory) }"
      >
        <factory-icon-display :icon="factory.icon" size="18" />
        <span class="ml-2">{{ factory.name || 'Unnamed factory' }}</span>
      </v-chip>
    </div>
  </div>
</template>

<script setup lang="ts">
  import { computed, nextTick, ref, watch } from 'vue'
  import { Factory, FactoryGroup } from '@/interfaces/planner/FactoryInterface'
  import { groupColorVars } from '@/utils/colors'
  import { calculateTotalPower } from '@/utils/statistics'
  import { formatMw } from '@/utils/numberFormatter'
  import {
    factoryStatusTallyChips,
    getFactoryStatuses,
    tallyFactoryStatuses,
  } from '@/utils/factory-management/status'
  import { useFactoryGroups } from '@/composables/useFactoryGroups'

  const props = defineProps<{
    group: FactoryGroup
    // 1-based place of the factory on screen among the group's factories.
    position: number
    factories: Factory[]
    // The factory on screen, marked in the row of the group's factories.
    currentId: number
  }>()

  const emit = defineEmits<{ (event: 'go', factory: Factory): void }>()

  // Only one of the group's factories is on screen, so the band carries the group's own power
  // balance rather than making you visit each member to find out what it costs.
  const power = computed(() => {
    const totals = calculateTotalPower(props.factories)
    return {
      produced: totals.totalPowerProduced,
      consumed: totals.totalPowerConsumed,
      difference: totals.totalPowerDifference,
      boost: totals.totalPowerBoost,
    }
  })

  // Counted the same way the Factories Summary counts the plan, from the same helper.
  const statusTally = computed(() => factoryStatusTallyChips(
    tallyFactoryStatuses(props.factories.map(factory => getFactoryStatuses(factory)))
  ))

  const { setGroupColor } = useFactoryGroups()

  // Where the row scrolls sideways (phones), bring the factory on screen into it. Set directly
  // rather than with scrollIntoView, which would scroll the page as well.
  const factoryRow = ref<HTMLElement | null>(null)
  watch(() => props.currentId, async () => {
    await nextTick()
    const row = factoryRow.value
    const chip = row?.querySelector<HTMLElement>('.band-factory-current')
    if (!row || !chip || row.scrollWidth <= row.clientWidth) return
    row.scrollLeft = chip.offsetLeft - row.offsetLeft - 12
  }, { immediate: true })

  const bandId = computed(() => `group-${props.group.id}`)

  const colorVars = computed(() => groupColorVars(props.group.color))
</script>

